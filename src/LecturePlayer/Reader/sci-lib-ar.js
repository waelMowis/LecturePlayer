/** تطبيع عربي للمقارنة: بلا تشكيل، والهمزات والتاء المربوطة والألف المقصورة موحدة، وبلا «ال» في الأول. */
export function normAr(s) {
  return String(s || "").replace(/[ً-ْـ]/g, "").replace(/[أإآٱ]/g, "ا").replace(/ة/g, "ه").replace(/ى/g, "ي").replace(/ؤ/g, "و").replace(/ئ/g, "ي")
    .trim().split(/\s+/).map(w => w.length > 3 && w.startsWith("ال") ? w.slice(2) : w.length > 4 && /^(وال|بال|كال|فال)/.test(w) ? w.slice(3) : w).join(" ");
}

export const GLOSS = new Map();       // عربي مطبّع ← [كلمات إنجليزية]
export const AR_OF = new Map();       // كلمة إنجليزية ← أول اسم عربي
for (const line of G.split("\n")) {
  const m = line.match(/^(.+?)=(.+)$/);
  if (!m) continue;
  const en = m[2].split("|"), k = normAr(m[1]);
  GLOSS.set(k, [...new Set([...(GLOSS.get(k) || []), ...en])]);
  if (!AR_OF.has(en[0])) AR_OF.set(en[0], m[1]);
}

